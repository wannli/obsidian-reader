import DOMPurify from 'dompurify';
import { webUrl } from '../core/model';
import { importedMarkdown } from '../core/annotations';
import { bounded, parseHtml } from './bounds';
import {
  assertNoTemplateDelimiters,
  assertSafeExternalText,
  assertSafeInlineCode,
} from './security';
import { preserveCode } from './code';

const forbidden = [
  'script',
  'style',
  'iframe',
  'object',
  'embed',
  'form',
  'input',
  'button',
  'textarea',
  'select',
  'link',
  'meta',
  'base',
  'video',
  'audio',
  'source',
  'svg',
  'math',
  'template',
  'noscript',
];
// Identity URLs drop hashes; content destinations must preserve their section/fragment targets.
const contentUrl = (value: string, base: string): string => {
  webUrl(value, base);
  return new URL(value, base).href;
};
export function fragment(html: string, base: string, vaultLinks = false): DocumentFragment {
  const template = parseHtml(html);
  // Inspect visibility while publisher styles still exist. Never compute page CSS or run scripts.
  for (const node of template.content.querySelectorAll<HTMLElement>(
    '[hidden],[aria-hidden],[style]',
  )) {
    const style = node.style ?? document.createElement('span').style;
    if (
      node.hasAttribute('hidden') ||
      node.getAttribute('aria-hidden')?.trim().toLowerCase() === 'true' ||
      style.display.toLowerCase() === 'none' ||
      ['hidden', 'collapse'].includes(style.visibility.toLowerCase()) ||
      style.getPropertyValue('content-visibility').toLowerCase() === 'hidden'
    )
      node.remove();
  }
  const result = DOMPurify.sanitize(template.content, {
    RETURN_DOM_FRAGMENT: true,
    FORBID_TAGS: forbidden,
    FORBID_ATTR: ['style', 'srcset', 'sizes', 'poster', 'autofocus', 'ping'],
    ALLOW_DATA_ATTR: false,
    ADD_ATTR: ['data-reader-src'],
  });
  for (const image of result.querySelectorAll('img')) {
    const src = image.getAttribute('src') ?? image.getAttribute('data-reader-src');
    image.removeAttribute('data-reader-src');
    image.removeAttribute('src');
    image.removeAttribute('srcset');
    if (src) {
      try {
        image.dataset.readerSrc = contentUrl(src, base);
      } catch {
        image.remove();
      }
    }
    image.loading = 'lazy';
    image.decoding = 'async';
    image.referrerPolicy = 'no-referrer';
  }
  for (const link of result.querySelectorAll('a[href]')) {
    const href = link.getAttribute('href')!;
    if (href.startsWith('#')) continue;
    // Wiki-link anchors generated by our renderer carry this exact class and a vault path.
    if (
      vaultLinks &&
      link.classList.contains('internal-link') &&
      !/^[a-z][\w+.-]*:/i.test(href) &&
      !href.startsWith('//')
    )
      continue;
    try {
      link.setAttribute('href', contentUrl(href, base));
      link.setAttribute('rel', 'noopener noreferrer');
    } catch {
      link.removeAttribute('href');
    }
  }
  return result;
}
export function plainText(html: string): string {
  const text =
    fragment(html, 'https://example.invalid/').textContent?.replace(/\s+/g, ' ').trim() ?? '';
  assertSafeExternalText(text);
  return text;
}
const entities = (text: string): string =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const destination = (url: string): string =>
  url.replace(/[\s<>"'`()[\]\\]/gu, (char) =>
    encodeURIComponent(char).replace(
      /[!'()*]/g,
      (c) => '%' + c.charCodeAt(0).toString(16).toUpperCase(),
    ),
  );
// Native Markdown may autolink prose even without an HTML anchor. Preserve the displayed bytes.
const prose = (text: string): string =>
  entities(text)
    .replace(/\b([a-z][a-z\d+.-]*):\/\//gi, '$1&#58;//')
    .replace(/\b(www)\./gi, '$1&#46;')
    .replace(/@/g, '&#64;');
export async function toMarkdown(html: string, base: string): Promise<string> {
  const safe = fragment(html, base);
  // Conversion happens in a template, never a live reading surface.
  const template = document.createElement('template');
  template.content.append(safe);
  assertNoTemplateDelimiters(template.content.textContent ?? '');
  for (const code of template.content.querySelectorAll('code')) {
    if (!code.closest('pre')) assertSafeInlineCode(code.textContent ?? '');
  }
  // No language is safe to delegate to native code-block processors: plugins can register any label.
  // Rebuild pre blocks with no info string; retain their literal bytes, not publisher attributes.
  const restoreCode = preserveCode(template.content);
  for (const code of template.content.querySelectorAll('code')) {
    for (const attr of [...code.attributes]) code.removeAttribute(attr.name);
  }
  // Encoded raw HTML must not reappear as active HTML/comments after conversion. Code is literal.
  const walker = document.createTreeWalker(template.content, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    if (!node.parentElement?.closest('pre,code')) node.textContent = prose(node.textContent ?? '');
  }
  for (const link of template.content.querySelectorAll('a[href]'))
    link.setAttribute('href', destination(link.getAttribute('href')!));
  for (const image of template.content.querySelectorAll<HTMLImageElement>('img[data-reader-src]')) {
    image.setAttribute('src', destination(image.dataset.readerSrc!));
    image.removeAttribute('data-reader-src');
    image.setAttribute(
      'alt',
      entities(image.getAttribute('alt') ?? '')
        .replace(/\s+/gu, ' ')
        .replace(/[\\`*_!]/g, '\\$&'),
    );
  }
  const { createMarkdownContent } = await import('defuddle/full');
  const markdown = bounded(
    restoreCode(
      importedMarkdown(bounded(createMarkdownContent(bounded(template.innerHTML), base)).trim()),
    ),
  );
  assertSafeExternalText(markdown);
  return markdown;
}
